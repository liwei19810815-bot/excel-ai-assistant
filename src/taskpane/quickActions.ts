/**
 * 预置提示词（快捷操作）。
 *
 * 【为什么需要】：业务人员打开一个空输入框，往往不知道能问什么。
 * 「用自然语言描述你想做的事」这句话对会用的人是废话，
 * 对不会用的人是障碍。给一排具体的起点，门槛低得多。
 *
 * 两条措辞原则：
 *
 * 1.【按症状写，不按功能写】。用户脑子里是"求和结果是 0"，
 *    不是"文本型数字转换"。工具箱的搜索框当初就是按这个原则做的，
 *    这里保持一致。
 *
 * 2.【prompt 要写得具体】。"清洗数据"这种含糊的指令会让模型乱猜范围，
 *    结果往往是改了不该改的地方。写清楚"哪一块、做什么、不做什么"。
 *
 * 【点击只填入输入框，不直接发送】。和工具箱搜索框"只带你去看说明、
 * 不执行命令"是同一个取舍：一键就改数据，省下的那次点击
 * 远不值得冒一次意外修改的风险。用户看一眼再回车。
 */

export interface QuickAction {
  id: string;
  /** 按钮上的短语，按症状写 */
  label: string;
  /** 填进输入框的完整描述 */
  prompt: string;
  group: string;
  /**
   * 会不会改动工作簿。
   * 【只用于界面标注】——真正的把关是 AI 的工具分级：
   * 改内容自动建快照可撤销，改结构强制确认。
   */
  mutates: boolean;
}

